open Why3
module P = Coq_agent_process
module V = Coq_agent_validation

let () =
  let root = Sysutil.concat (Sys.getcwd ()) "../.." in
  let main = Whyconf.get_main (Whyconf.default_config "") |> fun main ->
    Whyconf.set_libdir main (Filename.concat root "lib") in
  let available = ["coqtop"; "/usr/bin/coqtop"] |> List.filter_map (fun tool ->
    try Some (Unix.realpath (P.find_executable tool)) with _ -> None)
    |> List.sort_uniq String.compare in
  List.iter (fun executable ->
    let directory = P.directory "why3-coq-agent-compatibility-" in
    let version = P.run ~cwd:directory ~timeout:10. [executable; "-print-version"] in
    let version = List.hd (String.split_on_char ' ' (String.trim version.P.output)) in
    P.write_file (Filename.concat directory "BuiltIn.v")
      (P.read_file (Filename.concat root "lib/coq/BuiltIn.v"));
    let compiler = Filename.concat (Filename.dirname executable) "coqc" in
    let compiled = P.run ~cwd:directory ~timeout:30.
        [compiler; "-q"; "-R"; directory; "Why3"; "BuiltIn.v"] in
    if not (P.succeeds compiled) then failwith compiled.P.output;
    let prover = Whyconf.{
      prover = {prover_name="Coq";prover_version=version;prover_altern=""};
      command=Filename.quote executable ^ " -batch -R " ^ Filename.quote directory ^ " Why3 -l %f";
      command_steps=None;driver=None,"coq";in_place=false;editor="";interactive=true;
      agent=None;extra_options=[];extra_drivers=[]} in
    let source = "(* This file is generated by Why3's Coq driver *)\nRequire Import BuiltIn.\n\n" ^
      "Parameter i o2 : Z.\n\nAxiom H : (0 <= i)%Z.\n\n" ^
      "Axiom Ensures2 : o2 = (i + 2)%Z.\n\n" ^
      "(* Why3 assumption *)\nInductive shape : Type := tip | branch (x y:shape).\n\n" ^
      "(* Why3 assumption *)\nDefinition next (n:Z) : Z := (n + 1)%Z.\n\n" ^
      "(* Why3 goal *)\nTheorem target : (0 <= next o2)%Z.\n" ^
      "Proof. unfold next. pose proof Ensures2. pose proof H. lia. Qed.\n" in
    let subdir = P.directory "why3-agent-compatibility-validation-" in
    let validator = V.create ~main ~prover ~directory:subdir ~source ~timeout:20. ~memory:1000 in
    let candidate = Filename.concat directory "candidate.v" in
    P.write_file candidate ("Require Import Lia.\n" ^ source);
    (match V.check validator ~candidate with Ok _ -> () | Error e -> failwith (version ^ ": " ^ e));
    P.write_file candidate (Re.Str.global_replace
      (Re.Str.regexp_string "Proof. unfold next. pose proof Ensures2. pose proof H. lia. Qed.")
      "Admitted." source);
    (match V.check validator ~candidate with Error _ -> () | Ok _ -> failwith "admission accepted");
    Printf.printf "Coq %s compatibility check passed\n%!" version
  ) available
