open Why3
module P = Coq_agent_process
module V = Coq_agent_validation

let check message condition = if not condition then failwith message

let () =
  let root = Sysutil.concat (Sys.getcwd ()) "../.." in
  let main = Whyconf.get_main (Whyconf.default_config "") in
  let main = Whyconf.set_libdir main (Filename.concat root "lib") in
  let executable = try P.find_executable "coqtop" with Coq_agent_config.Error _ -> "" in
  if executable = "" then print_endline "SKIP: Coq is not installed" else begin
    let directory = P.directory "why3-agent-validation-test-" in
    let version = P.run ~cwd:directory ~timeout:10. [executable; "-print-version"] in
    let version = List.hd (String.split_on_char ' ' (String.trim version.P.output)) in
    let prover = Whyconf.{
      prover = {prover_name = "Coq"; prover_version = version; prover_altern = ""};
      command = Filename.quote executable ^ " -batch -R %l/coq Why3 -l %f";
      command_steps = None; driver = None, "coq"; in_place = false;
      editor = ""; interactive = true; agent = None; extra_options = []; extra_drivers = [];
    } in
    let source = "(* This file is generated by Why3's Coq driver *)\nRequire Import BuiltIn.\n\n" ^
      "Parameter n : Z.\n\nAxiom hn : (0 <= n)%Z.\n\n" ^
      "(* Why3 goal *)\nTheorem target : (0 <= n + 1)%Z.\nProof.\n\nQed.\n" in
    let validator = V.create ~main ~prover ~directory ~source ~timeout:20. ~memory:1000 in
    let candidate = Filename.concat directory "candidate.v" in
    let test name context statement proof expected =
      let text = "(* This file is generated by Why3's Coq driver *)\nRequire Import BuiltIn.\n\n" ^
        "Parameter n : Z.\n\nAxiom hn : (0 <= n)%Z.\n\n" ^ context ^
        "\n(* Why3 goal *)\nTheorem target : " ^ statement ^ ".\n" ^ proof ^ "\n" in
      P.write_file candidate text;
      let result = V.check validator ~candidate in
      let accepted = match result with Ok _ -> true | Error _ -> false in
      if accepted <> expected then failwith (name ^ ": " ^
        (match result with Ok _ -> "unexpectedly accepted" | Error e -> e));
      Printf.printf "%s: %s\n%!" name (if accepted then "accepted" else "rejected") in
    test "valid proof with generated assumptions" "Require Import Lia.\n"
      "(0 <= n + 1)%Z" "Proof. pose proof hn. lia. Qed." true;
    test "changed theorem statement" "" "True" "Proof. exact I. Qed." false;
    test "changed statement rejected even with a proof of original VC" "Require Import Lia.\n"
      "True" "Proof. pose proof hn. lia. Qed." false;
    test "admitted theorem" "" "(0 <= n + 1)%Z" "Admitted." false;
    test "aborted theorem" "" "(0 <= n + 1)%Z" "Proof. Abort." false;
    test "admitted helper" "Lemma helper : False. Admitted.\n"
      "(0 <= n + 1)%Z" "Proof. exfalso. exact helper. Qed." false;
    test "new axiom in proof" "" "(0 <= n + 1)%Z"
      "Proof. assert (False) by admit. admit. Admitted." false;
    test "unchecked cast" "" "(0 <= n + 1)%Z"
      "Proof. exact_no_check I. Qed." false;
    test "unused admitted helper" "Lemma helper : True. Admitted.\nRequire Import Lia.\n"
      "(0 <= n + 1)%Z" "Proof. pose proof hn. lia. Qed." false;
    test "shadowed generated symbol" "Definition n : Z := 0%Z.\nRequire Import Lia.\n"
      "(0 <= n + 1)%Z" "Proof. unfold n. lia. Qed." false;
    test "imported module shadows generated symbol"
      "Module Shadow. Definition n : Z := 0%Z. End Shadow.\nImport Shadow.\nRequire Import Lia.\n"
      "(0 <= n + 1)%Z" "Proof. unfold n. lia. Qed." false;
    test "notation changes generated statement"
      "Notation \"x <= y\" := True (at level 70, no associativity) : Z_scope.\n"
      "(0 <= n + 1)%Z" "Proof. exact I. Qed." false;
    test "unsafe recursive definition" "Unset Guard Checking.\nFixpoint loop (x:nat) : False := loop x.\n"
      "(0 <= n + 1)%Z" "Proof. exfalso. exact (loop 0%nat). Qed." false;
    test "disguised ML command" "Declare (* nested (* comment *) *)\nML Module \"bad\".\n"
      "(0 <= n + 1)%Z" "Admitted." false;
    test "top-level helper requires migration" "Require Import Lia.\nLemma helper : (0 <= n + 1)%Z.\nProof. pose proof hn. lia. Qed.\n"
      "(0 <= n + 1)%Z" "Proof. exact helper. Qed." false;
    test "proved local helper" "Require Import Lia.\n" "(0 <= n + 1)%Z"
      "Proof. assert (helper : (0 <= n + 1)%Z) by (pose proof hn; lia). exact helper. Qed." true;
    let prelude_import = Re.Str.global_replace (Re.Str.regexp_string "Require Import BuiltIn.")
        "Require Import BuiltIn.\nRequire Import Lia." source in
    let prelude_import = Re.Str.global_replace (Re.Str.regexp_string "Proof.\n\nQed.")
        "Proof. pose proof hn. lia. Qed." prelude_import in
    P.write_file candidate prelude_import;
    (match V.check validator ~candidate with
     | Ok canonical ->
         let after part = Re.Str.search_forward (Re.Str.regexp_string part) canonical 0 in
         check "import moved after the immutable theorem declaration"
           (after "Require Import Lia." > after "Proof.")
     | Error e -> failwith ("import in generated prelude: " ^ e));
    P.write_file candidate (Re.Str.global_replace
      (Re.Str.regexp_string "Require Import BuiltIn.")
      "Require Import BuiltIn.\nRequire Import Lia. Load \"missing.v\"." prelude_import);
    (match V.check validator ~candidate with
     | Error _ -> ()
     | Ok _ -> failwith "unsafe command recovered from generated prelude");
    test "early successful exit cannot reuse an old object" "Quit.\n"
      "(0 <= n + 1)%Z" "Proof. exact I. Qed." false;
    (* Use the real original-Coq regeneration path. With an imported baseline,
       [pose proof Ensures2] introduces a local H which shadows the imported H;
       in the normal standalone script Coq avoids that global name. *)
    let env = Env.create_env [Filename.concat root "stdlib"] in
    let main = Whyconf.set_datadir main root in
    let driver = Driver.load_driver_for_prover main env prover in
    let whyfile = Filename.concat directory "names.why" in
    P.write_file whyfile
      "theory Names\n use int.Int\n constant i: int\n constant o2: int\n axiom H: 0 <= i\n axiom Ensures2: o2 = i + 2\n goal target: 0 <= o2\nend\n";
    let theories, _ = Env.read_file Env.base_language env whyfile in
    let theory = Wstdlib.Mstr.find "Names" theories in
    let task = List.hd (Task.split_theory theory None None) in
    let render ?old () = Format.asprintf "%t" (fun fmt -> Driver.print_task ?old driver fmt task) in
    let original = render () in
    let subdir = P.directory "why3-agent-standalone-names-" in
    let names = V.create ~main ~prover ~directory:subdir ~source:original ~timeout:20. ~memory:1000 in
    let completed = "Require Import Lia.\n\n" ^
      Re.Str.global_replace (Re.Str.regexp_string "Proof.\n")
        "Proof.\npose proof Ensures2. pose proof H. lia.\n" original in
    P.write_file candidate completed;
    (match V.check ~regenerate:(fun old -> render ~old ()) names ~candidate with
     | Error e -> failwith ("standalone automatic hypothesis names: " ^ e)
     | Ok canonical ->
         let approved = Coq_agent_script.prepare (Coq_agent_script.create original) completed in
         P.write_file candidate approved;
         let channel = open_in candidate in
         let regenerated = Fun.protect ~finally:(fun () -> close_in_noerr channel)
             (fun () -> render ~old:channel ()) in
         check "checked source is ordinary Coq regeneration" (canonical = regenerated);
         check "gate normalization is stable" (P.read_file candidate = approved);
         (* Replay must preserve the same standalone context and proof. *)
         P.write_file candidate canonical;
         match V.check ~regenerate:(fun old -> render ~old ()) names ~candidate with
         | Ok replay -> check "regeneration is stable on replay" (replay = canonical)
         | Error e -> failwith ("standalone replay: " ^ e));
    print_endline "standalone automatic hypothesis names: accepted with ordinary Coq regeneration";
    let prelude = Re.Str.global_replace (Re.Str.regexp_string "Require Import BuiltIn.")
        "Require Import BuiltIn.\nRequire Import Lia." original in
    let prelude = Re.Str.global_replace (Re.Str.regexp_string "Proof.\n")
        "Proof.\npose proof Ensures2. pose proof H. lia.\n" prelude in
    P.write_file candidate prelude;
    (match V.check ~regenerate:(fun old -> render ~old ()) names ~candidate with
     | Error e -> failwith ("standalone prelude imports: " ^ e)
     | Ok canonical ->
         P.write_file candidate canonical;
         match V.check ~regenerate:(fun old -> render ~old ()) names ~candidate with
         | Ok replay -> check "recovered prelude import survives replay" (replay = canonical)
         | Error e -> failwith ("standalone prelude import replay: " ^ e));
    let polymorphic = "(* This file is generated by Why3's Coq driver *)\n\n" ^
      "(* Why3 goal *)\nTheorem poly (a:Type) (x:a) : x = x.\nProof. reflexivity. Qed.\n" in
    let subdir = Filename.concat directory "polymorphic" in
    Unix.mkdir subdir 0o700;
    let validator = V.create ~main ~prover ~directory:subdir ~source:polymorphic ~timeout:20. ~memory:1000 in
    P.write_file candidate polymorphic;
    check "polymorphic theorem" (match V.check validator ~candidate with Ok _ -> true | _ -> false);
    let unsound = Re.Str.global_replace (Re.Str.regexp_string "(0 <= n + 1)%Z")
        "n = 0%Z" source in
    let subdir = P.directory "why3-agent-reset-regression-" in
    let validator = V.create ~main ~prover ~directory:subdir ~source:unsound ~timeout:20. ~memory:1000 in
    P.write_file candidate (Re.Str.global_replace (Re.Str.regexp_string "(* Why3 goal *)")
      ("Reset n.\nDefinition n : Z := 0%Z.\n" ^
       "Definition hn : (0 <= n)%Z := Z.le_refl 0.\n\n(* Why3 goal *)")
      (Re.Str.global_replace (Re.Str.regexp_string "Proof.\n\nQed.")
        "Proof. reflexivity. Qed." unsound));
    check "Reset specialization of a false VC rejected"
      (match V.check validator ~candidate with Error _ -> true | _ -> false);
    (* A compiler-only implementation would accept this valid proof despite the
       configured original backend refusing it. Require that backend to run. *)
    let wrapped = P.directory "why3-agent-original-command-" in
    let wrapper = Filename.concat wrapped "coqtop" in
    P.write_file wrapper ("#!/bin/sh\nfor arg do\n" ^
      "  if [ \"$arg\" = \"-l\" ]; then echo ORIGINAL-COQ-COMMAND-RAN; exit 1; fi\ndone\n" ^
      "exec " ^ Filename.quote executable ^ " \"$@\"\n");
    Unix.chmod wrapper 0o700;
    List.iter (fun name -> Unix.symlink (Filename.concat (Filename.dirname executable) name)
      (Filename.concat wrapped name)) ["coqc"; "coqchk"];
    let wrapped_prover = {prover with Whyconf.command =
      Filename.quote wrapper ^ " -batch -R %l/coq Why3 -l %f"} in
    let subdir = P.directory "why3-agent-original-command-validation-" in
    let validator = V.create ~main ~prover:wrapped_prover ~directory:subdir ~source ~timeout:20. ~memory:1000 in
    P.write_file candidate ("Require Import Lia.\n" ^ Re.Str.global_replace
      (Re.Str.regexp_string "Proof.\n\nQed.") "Proof. pose proof hn. lia. Qed." source);
    (match V.check validator ~candidate with
     | Error e -> check "configured original Coq command is mandatory"
         (try ignore (Re.Str.search_forward (Re.Str.regexp_string "ORIGINAL-COQ-COMMAND-RAN") e 0); true
          with Not_found -> false)
     | Ok _ -> failwith "configured original Coq backend was bypassed");
    let library = P.directory "why3-agent-unapproved-library-" in
    P.write_file (Filename.concat library "Evil.v") "Axiom bad : False.\n";
    let compiler = Filename.concat (Filename.dirname executable) "coqc" in
    let compiled = P.run ~cwd:library ~timeout:10.
        [compiler;"-q";"-Q";library;"Unapproved";"Evil.v"] in
    check "negative dependency fixture compiled" (P.succeeds compiled);
    let prover = {prover with Whyconf.extra_options=["-Q";library;"Unapproved"]} in
    let subdir = P.directory "why3-agent-dependency-validation-" in
    let validator = V.create ~main ~prover ~directory:subdir ~source ~timeout:20. ~memory:1000 in
    P.write_file candidate ("Require Import Unapproved.Evil.\n" ^
      Re.Str.global_replace (Re.Str.regexp_string "Proof.\n\nQed.")
        "Proof. exfalso. exact bad. Qed." source);
    check "imported unauthorized assumption rejected"
      (match V.check validator ~candidate with Error _ -> true | _ -> false);
    let fixture ~source filename =
      let source = P.read_file source in
      let subdir = P.directory "why3-agent-validation-fixture-" in
      let validator = V.create ~main ~prover ~directory:subdir ~source ~timeout:20. ~memory:1000 in
      match V.check validator ~candidate:filename with
      | Ok _ -> Printf.printf "%s: accepted\n%!" filename
      | Error e -> failwith (filename ^ ": " ^ e) in
    (match Array.to_list Sys.argv with
     | [_; "--frozen-source"; source; filename] -> fixture ~source filename
     | _ :: filenames -> List.iter (fun filename -> fixture ~source:filename filename) filenames
     | [] -> assert false);
    check "validation leaves original source unchanged" (String.length source > 0);
    print_endline "Coq agent validation tests passed"
  end
